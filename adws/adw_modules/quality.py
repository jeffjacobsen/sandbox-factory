"""Deterministic lint, typecheck, build and test blocks.

DO NOT EDIT THIS FILE TO CUSTOMISE A PROJECT. Every command lives in the
`quality:` block of sssf.config.yaml; the function names here are permanent and
the ADWs import them by name.

That rule is not style. The repo this came from customised by editing: it
hardcoded its app paths here and renamed `run_tests` to `run_inkwell_tests`.
Three ADWs kept calling the old name and failed at the TAIL of their chains,
after the planner and the builder had already spent — ~$0.96 per run, and the
same class of failure recurs in every stamped repo that edits a stamped file.

`/sssf install --check` reports when this file has drifted from the template.
"""

from __future__ import annotations

import os
import shlex
import subprocess
import time
from pathlib import Path

from .data_types import (EventRecord, QualityCheckResult, QualityCheckSpec, QualityResult,
                         VerifyOutput)
from .utils import now_iso, operator_env

# How much of a failing command's output rides back inside the envelope. Enough
# for a builder to act on without opening the artifact; bounded so a runaway
# stack trace can't swamp the next agent's context.
TAIL_CHARS = 4_000


# Invoked by bare name, exactly as the operator would type it: an ADW inherits
# their environment, so `bun` resolves off PATH here for the same reason it does
# in their shell. Resolving it to an absolute path instead would hard-code one
# machine's layout into the trace and into the artifact logs.
#
# BUN_PATH remains the escape hatch for an environment that does NOT put bun on
# PATH — a container, or a cron with a stripped PATH. A genuinely missing binary
# is not something to pre-empt: _run's OSError branch already records it as
# exit 127 with the real error text.
BUN = os.environ.get("BUN_PATH", "").strip() or "bun"


def _check_dir(run, name: str) -> Path:
    seq = run.phases[-1].seq if run.phases else 0
    path = run.context_handoff_dir / "quality" / f"{seq:02d}_{name}"
    path.mkdir(parents=True, exist_ok=True)
    return path


def _run(spec: QualityCheckSpec, run) -> QualityCheckResult:
    phase = run.phases[-1]
    output_dir = _check_dir(run, spec.name)
    output_artifact = output_dir / "command.log"
    command = shlex.join(spec.argv)
    env = operator_env()             # the engineer's own shell environment

    run.console.note(f"quality {spec.name}: {command}")
    started_at = now_iso()
    clock = time.monotonic()
    stdout = ""
    stderr = ""
    try:
        completed = subprocess.run(
            spec.argv,
            cwd=run.repo_root,
            env=env,
            capture_output=True,
            text=True,
            timeout=spec.timeout_seconds,
        )
        returncode = completed.returncode
        stdout = completed.stdout
        stderr = completed.stderr
    except subprocess.TimeoutExpired as error:
        returncode = 124
        stdout = error.stdout or ""
        stderr = (error.stderr or "") + f"\nTimed out after {spec.timeout_seconds}s."
    except OSError as error:
        returncode = 127
        stderr = str(error)

    duration = time.monotonic() - clock
    output_artifact.write_text(
        f"$ {command}\nexit: {returncode}\nduration_seconds: {duration:.3f}\n"
        f"\n--- stdout ---\n{stdout}\n--- stderr ---\n{stderr}\n"
    )
    passed = returncode == 0
    run.tracer.event(EventRecord(
        adw_id=run.adw_id,
        phase_id=phase.phase_id,
        type="tool_call",
        name=f"quality:{spec.name}",
        payload={
            "area": spec.area,
            "operation": spec.operation,
            "command": command,
            "returncode": returncode,
            "passed": passed,
            "output_artifact": str(output_artifact),
        },
        started_at=started_at,
        ended_at=now_iso(),
    ))
    run.console.note(
        f"quality {spec.name}: {'passed' if passed else 'failed'} "
        f"(exit {returncode}, {duration:.1f}s)"
    )
    return QualityCheckResult(
        name=spec.name,
        area=spec.area,
        operation=spec.operation,
        command=command,
        returncode=returncode,
        passed=passed,
        duration_seconds=duration,
        output_artifact=str(output_artifact),
        output_tail=(stdout + stderr)[-TAIL_CHARS:],
    )


def _spec(cfg, run) -> QualityCheckSpec:
    """One configured check, with {output_dir} resolved.

    Build and typecheck commands need somewhere to put their bundle, and that
    somewhere is per-run — it lives under the session's handoff dir so the
    evidence travels with the run. The manifest cannot know that path, so it
    writes the placeholder and this resolves it.
    """
    out = str(_check_dir(run, cfg.name) / "bundle")
    return QualityCheckSpec(
        name=cfg.name,
        area=cfg.area,
        operation=cfg.operation,
        argv=[a.replace("{output_dir}", out) for a in cfg.argv],
        timeout_seconds=cfg.timeout_seconds,
    )


def tests(run) -> QualityCheckResult:
    """Run the project's suite. A known command — code, not an agent.

    The command is written down once, in config, because it is not a judgement
    call. An agent rediscovering `bun test` on every run cost ~1M tokens and 85s;
    this costs nothing and takes milliseconds.
    """
    argv = list(run.cfg.quality.test)
    if not argv:
        raise ValueError(
            "no quality.test command in the config. Add one to the `quality:` "
            "block — this is project data, not something to hardcode here."
        )
    return _run(QualityCheckSpec(
        name="tests",
        area="backend",
        operation="build",           # the enum has no "test"; the name carries it
        argv=argv,
        timeout_seconds=run.cfg.quality.test_timeout_seconds,
    ), run)


def run_tests(run) -> QualityResult:
    """The test suite as a QualityResult, so it reports like every other block.

    THIS NAME IS PERMANENT. It was once renamed to `run_inkwell_tests` to mark
    that it ran one project's suite; three ADWs kept calling the old name and
    failed at the tail of their chains, ~$0.96 in. The project-specific part is
    the argv in config, never the identifier the ADWs import.
    """
    check = tests(run)
    failures = ([] if check.passed else
                [f"{check.name}: `{check.command}` exited {check.returncode}\n"
                 f"{check.output_tail}".rstrip()])
    return QualityResult(passed=check.passed, checks=[check], failures=failures,
                         artifacts=[check.output_artifact])


def run_quality(run) -> QualityResult:
    """Every check the config declares, in declaration order."""
    checks = [_run(_spec(c, run), run) for c in run.cfg.quality.checks]
    failures = [f"{c.name}: `{c.command}` exited {c.returncode}\n{c.output_tail}".rstrip()
                for c in checks if not c.passed]
    return QualityResult(passed=not failures, checks=checks, failures=failures,
                         artifacts=[c.output_artifact for c in checks])


def as_envelope(result: QualityResult, what: str) -> VerifyOutput:
    """Wrap a deterministic result so the builder can be handed it directly."""
    return VerifyOutput(
        status="success" if result.passed else "fail",
        summary=(f"{what}: all {len(result.checks)} check(s) passed" if result.passed
                 else f"{what}: {len(result.failures)} of {len(result.checks)} check(s) failed"),
        artifacts=result.artifacts,
        notes_for_next_agent=("" if result.passed else
                              "Fix every failure below. The output is verbatim from the "
                              "command — trust it over any summary."),
        passed=result.passed,
        failures=result.failures,
    )
